public enum TipoEnum
{
    // Inizializzato a 1 (i valori successivi saranno incrementati automaticamente).
    Liscia = 1,   // Carta molto uniforme e scorrevole. Usata per stampanti, fotocopie e scrittura.
    Ruvida,       // Superficie granulosa. Ideale per disegno a matita, carboncino o tecniche artistiche.
    Opaca,        // Non riflette la luce. Buona per testi e documenti perché affatica meno la vista.
